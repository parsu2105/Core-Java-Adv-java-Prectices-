package com.kodewala;

public class EvenOrOdd {

	public static void main(String[] args) {
		int marks=80;
		if(marks>=90) {
			System.out.println("GRADE 'A' ");
		}else if(marks> 75) {
			System.out.println("GRADE 'B' ");
		}else if(marks>60) {
			System.out.println("GRADE 'C' ");
		}else {
			System.out.println("FAIL");
		}

	}

}
